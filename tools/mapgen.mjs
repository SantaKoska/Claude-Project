// Project India states + Kerala districts + world land to ready-made SVG paths.
// Data: datameet/maps (MIT, Survey of India boundaries) and Natural Earth land (public domain).
// Usage: node tools/mapgen.mjs   -> lib/maps/india_kerala.js  (window.MAP)
// Needs d3-geo + topojson-client: NODE_PATH=<dir with node_modules> node tools/mapgen.mjs
import fs from 'fs'; import path from 'path'; import { createRequire } from 'module';
const require = createRequire(import.meta.url);
const d3 = require('d3-geo'); 
const R = p => fix(JSON.parse(fs.readFileSync(p, 'utf8')));
// d3-geo wants clockwise outer rings; GeoJSON from mapshaper is counter-clockwise, which d3 reads as "the whole globe minus this shape"
function fix(fc) { (fc.features || []).forEach(f => { const g = f.geometry; if (!g) return; const polys = g.type === 'Polygon' ? [g.coordinates] : g.type === 'MultiPolygon' ? g.coordinates : [];
  polys.forEach(rings => { if (d3.geoArea({ type: 'Polygon', coordinates: [rings[0]] }) > 2 * Math.PI) rings.forEach(r => r.reverse()); }); }); return fc; }
const states = R('tools/mapdata/india_states.geojson'), dist = R('tools/mapdata/kerala_districts.geojson');
const land = R('tools/mapdata/land_region.geojson'); // Natural Earth 50m land clipped to 30E-120E, 20S-45N
const india = { type: 'FeatureCollection', features: states.features };
const proj = d3.geoMercator().fitExtent([[60, 380], [1020, 1480]], india);
proj.clipExtent([[-1500, -1500], [2580, 3420]]);
const gp = d3.geoPath(proj).digits(1);
const k = proj.scale(), [tx, ty] = proj.translate();
const ml = { Thiruvananthapuram: 'തിരുവനന്തപുരം', Kollam: 'കൊല്ലം', Pathanamthitta: 'പത്തനംതിട്ട', Alappuzha: 'ആലപ്പുഴ', Kottayam: 'കോട്ടയം', Idukki: 'ഇടുക്കി', Ernakulam: 'എറണാകുളം', Thrissur: 'തൃശ്ശൂർ', Palakkad: 'പാലക്കാട്', Malappuram: 'മലപ്പുറം', Kozhikode: 'കോഴിക്കോട്', Wayanad: 'വയനാട്', Kannur: 'കണ്ണൂർ', Kasaragod: 'കാസർഗോഡ്' };
const feat = f => { const [cx, cy] = gp.centroid(f); const b = gp.bounds(f); return { d: gp(f), cx: +cx.toFixed(1), cy: +cy.toFixed(1), box: b.flat().map(v => +v.toFixed(1)) }; };
const out = {
  note: 'Mercator; x = tx + k*lon_rad, y = ty - k*ln(tan(pi/4 + lat_rad/2)). Boundaries: Survey of India via datameet/maps (MIT).',
  k, tx, ty, size: [1080, 1920],
  land: gp(land),
  states: states.features.map(f => Object.assign({ name: f.properties.ST_NM }, feat(f))),
  kerala: feat(states.features.find(f => f.properties.ST_NM === 'Kerala')),
  districts: dist.features.map(f => Object.assign({ name: f.properties.DISTRICT, ml: ml[f.properties.DISTRICT] }, feat(f))),
  india: gp(india),
};
fs.writeFileSync('lib/maps/india_kerala.js', '/* generated by tools/mapgen.mjs - do not edit */\nwindow.MAP=' + JSON.stringify(out) + ';\n' +
  'window.MAP.xy=function(lon,lat){var r=Math.PI/180;var M=window.MAP;return[M.tx+M.k*lon*r,M.ty-M.k*Math.log(Math.tan(Math.PI/4+lat*r/2))];};\n');
console.log('wrote lib/maps/india_kerala.js', (fs.statSync('lib/maps/india_kerala.js').size / 1024).toFixed(0) + ' KB', 'states', out.states.length, 'districts', out.districts.length);
